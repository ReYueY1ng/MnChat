/// 生成 `<框名>: <获取途径>` 说明文案。
///
/// - 默认框（id=1）返回 [kDefaultHeadFrameCaption]（游戏特判 `StringID == 5300`）；
/// - 未收录的 id 回退到既有占位 `头像框 #<id>`（绝不编造获取途径）；
/// - 获取途径为空时只显示名称（避免出现 `名称: ` 悬空冒号）。
String headFrameCaption(int id) {
  if (id == 1) return kDefaultHeadFrameCaption;
  final entry = kHeadFrameCatalog[id];
  if (entry == null) return '头像框 #$id';
  return entry.getWay.isEmpty ? entry.name : '${entry.name}: ${entry.getWay}';
}
