/// 坐骑头像图标资源路径：`assets/rideicons/<id>.webp`（WebP）。
String rideIconAsset(int id) => 'assets/rideicons/$id.webp';

/// 按头像本体 (type,id) 解析本地图标资源路径；无对应图标时返回 null。
///
/// type：1=皮肤（id 为皮肤 ID，经 [kSkinHeadIcon] 映射到 Head 图标）
/// 3=坐骑 4=立绘。type 2（头套，3D 组合部件）无本地图，返回 null。
String? headIconAsset(int type, int id) {
  switch (type) {
    case 1:
      final head = kSkinHeadIcon[id];
      return head == null ? null : roleIconAsset(head);
    case 3:
      return rideIconAsset(id);
    case 4:
      return roleIconAsset(id);
    default:
      return null;
  }
}
